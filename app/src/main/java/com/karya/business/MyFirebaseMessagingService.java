package com.karya.business;

import android.app.Notification;
import android.app.NotificationChannel;
import android.app.NotificationManager;
import android.app.PendingIntent;
import android.content.Context;
import android.content.Intent;
import android.content.SharedPreferences;
import android.media.RingtoneManager;
import android.net.Uri;
import android.os.Build;
import android.os.PowerManager;
import android.util.Log;
import androidx.annotation.NonNull;
import androidx.core.app.NotificationCompat;
import com.google.firebase.messaging.FirebaseMessagingService;
import com.google.firebase.messaging.RemoteMessage;
import java.util.Map;

public class MyFirebaseMessagingService extends FirebaseMessagingService {

    private static final String TAG = "VMH_FCM_Service";
    public static final String CHANNEL_ID = "karya_business_channel_v3";

    @Override
    public void onNewToken(@NonNull String token) {
        super.onNewToken(token);
        Log.d(TAG, "Refreshed FCM Token: " + token);
        SharedPreferences prefs = getSharedPreferences("VMH_PREFS", Context.MODE_PRIVATE);
        prefs.edit().putString("fcm_token", token).putBoolean("fcm_token_synced", false).apply();
    }

    @Override
    public void onMessageReceived(@NonNull RemoteMessage remoteMessage) {
        super.onMessageReceived(remoteMessage);
        Log.d(TAG, "FCM Message received from: " + remoteMessage.getFrom());

        Map<String, String> data = remoteMessage.getData();
        String senderDeviceId = data.get("senderDeviceId");

        // Suppress notifications generated by this same device
        SharedPreferences prefs = getSharedPreferences("VMH_PREFS", Context.MODE_PRIVATE);
        String myDeviceId = prefs.getString("device_id", "");
        if (senderDeviceId != null && !senderDeviceId.isEmpty()) {
            String cleanSender = senderDeviceId.replace("android_", "").replace("web_", "").trim();
            String cleanMyId = myDeviceId.replace("android_", "").replace("web_", "").trim();
            if (cleanSender.equalsIgnoreCase(cleanMyId)) {
                Log.d(TAG, "Ignoring self-generated notification from device: " + senderDeviceId);
                return;
            }
        }

        String title = data.get("title");
        String body = data.get("body");

        if (title == null || title.isEmpty()) {
            if (remoteMessage.getNotification() != null) {
                title = remoteMessage.getNotification().getTitle();
            }
            if (title == null || title.isEmpty()) {
                title = "🏛️ वर्मा मैरिज हॉल";
            }
        }

        if (body == null || body.isEmpty()) {
            if (remoteMessage.getNotification() != null) {
                body = remoteMessage.getNotification().getBody();
            }
            if (body == null || body.isEmpty()) {
                body = "नई गतिविधि या बुकिंग अपडेट प्राप्त हुआ।";
            }
        }

        showNotification(title, body, data);
    }

    private void showNotification(String title, String body, Map<String, String> data) {
        try {
            // Wake up device screen briefly so user sees the notification even when phone is locked
            PowerManager pm = (PowerManager) getSystemService(Context.POWER_SERVICE);
            if (pm != null) {
                PowerManager.WakeLock wakeLock = pm.newWakeLock(
                        PowerManager.FULL_WAKE_LOCK |
                        PowerManager.ACQUIRE_CAUSES_WAKEUP |
                        PowerManager.ON_AFTER_RELEASE,
                        "VMH:NotificationWakeLock"
                );
                wakeLock.acquire(4000);
            }
        } catch (Exception e) {
            Log.w(TAG, "Could not acquire WakeLock: " + e.getMessage());
        }

        ensureNotificationChannel();

        Intent intent = new Intent(this, MainActivity.class);
        intent.addFlags(Intent.FLAG_ACTIVITY_CLEAR_TOP | Intent.FLAG_ACTIVITY_SINGLE_TOP);
        if (data != null) {
            for (Map.Entry<String, String> entry : data.entrySet()) {
                intent.putExtra(entry.getKey(), entry.getValue());
            }
        }

        PendingIntent pendingIntent = PendingIntent.getActivity(
                this,
                (int) System.currentTimeMillis(),
                intent,
                PendingIntent.FLAG_UPDATE_CURRENT | PendingIntent.FLAG_IMMUTABLE
        );

        Uri soundUri = RingtoneManager.getDefaultUri(RingtoneManager.TYPE_NOTIFICATION);

        int iconRes = getApplicationInfo().icon;
        if (iconRes == 0) {
            iconRes = android.R.drawable.stat_notify_chat;
        }

        NotificationCompat.Builder builder = new NotificationCompat.Builder(this, CHANNEL_ID)
                .setSmallIcon(iconRes)
                .setContentTitle(title)
                .setContentText(body)
                .setStyle(new NotificationCompat.BigTextStyle().bigText(body))
                .setAutoCancel(true)
                .setSound(soundUri)
                .setVibrate(new long[]{0, 500, 250, 500})
                .setPriority(NotificationCompat.PRIORITY_MAX)
                .setVisibility(NotificationCompat.VISIBILITY_PUBLIC)
                .setCategory(NotificationCompat.CATEGORY_EVENT)
                .setContentIntent(pendingIntent);

        NotificationManager nm = (NotificationManager) getSystemService(Context.NOTIFICATION_SERVICE);
        if (nm != null) {
            int notificationId = (int) (System.currentTimeMillis() % 100000);
            nm.notify(notificationId, builder.build());
            Log.d(TAG, "Push notification displayed successfully (ID: " + notificationId + "): " + title);
        }
    }

    private void ensureNotificationChannel() {
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) {
            NotificationManager nm = getSystemService(NotificationManager.class);
            if (nm != null && nm.getNotificationChannel(CHANNEL_ID) == null) {
                CharSequence name = "व्यापार सिंक अलर्ट्स";
                String description = "नए बिल और मैरिज हॉल बुकिंग के नोटिफिकेशन";
                int importance = NotificationManager.IMPORTANCE_HIGH;
                NotificationChannel channel = new NotificationChannel(CHANNEL_ID, name, importance);
                channel.setDescription(description);
                channel.enableVibration(true);
                channel.setVibrationPattern(new long[]{0, 500, 250, 500});
                channel.setLockscreenVisibility(Notification.VISIBILITY_PUBLIC);
                channel.setShowBadge(true);
                nm.createNotificationChannel(channel);
            }
        }
    }
}
